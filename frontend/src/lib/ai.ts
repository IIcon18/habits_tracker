const GENERIC = ['сделать самый первый шаг', 'подготовить всё нужное', 'заняться этим одну минуту', 'просто начать и остановиться', 'положить нужное на видное место', 'сделать самую маленькую часть'];

/** Возвращает 3 варианта; page — номер набора для «Ещё варианты». */
export async function suggestMini(full: string, page = 0): Promise<string[]> {
  const pool = CANNED.find(([re]) => re.test(full))?.[1] ?? GENERIC;
  // Имитируем сетевую задержку, чтобы было видно состояние загрузки (экран 4.2).
  await new Promise((r) => setTimeout(r, 900));
  const start = (page * 3) % pool.length;
  return [0, 1, 2].map((i) => pool[(start + i) % pool.length]);
}
